        "",
        "The structured evidence each system grounds its answers in is itself a set"
        " of",
        "predicted edges, so the tier-2 checks"
        " (`pinakes_ml.consistency`) run over",
        "it — descent acyclicity, canonical-schema `from`/`to` type constraints, and",
        "relation antisymmetry. The retrieved evidence is drawn from real corpus"
        " edges,",
        "so any breach here is a genuine corpus/schema observation (e.g."
        " `DESCENDS_FROM`",
        "edges among node types the schema's `from`/`to` sets do not yet declare),"
        " not a",
