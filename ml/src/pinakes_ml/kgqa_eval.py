"""KGQA evaluation — the third eval tier (NEUROSYMBOLIC_ROADMAP.md Phase 5, US-004).

The eval harness has three tiers, all judging a model/system against the same
corpus but from different angles:

* **tier 1** — link-prediction metrics (MRR / Hits@k), the *statistical* floor
  (:mod:`pinakes_ml.baselines`, ``docs/ml-baselines.md`` "Results").
* **tier 2** — logical consistency, the *symbolic* ratchet
  (:mod:`pinakes_ml.consistency`, ``docs/ml-baselines.md`` "Logical consistency").
* **tier 3** — KGQA accuracy on the held-out split (this module): does a system
  *answer the reasoning questions correctly*, and is its answer *grounded in the
  retrieved evidence*.

Everything here is a **pure** function of the held-out QA records + the corpus
graph (no wall-clock, no network, no live Neo4j, no torch), so the committed
baseline (``ml/manifests/kgqa-eval-baseline.json``) is byte-reproducible and the
scorer is unit-tested with tiny fixtures — the same reproducible-artifact pattern
as the rest of the workspace (see ``ml/CLAUDE.md``). The thin CLI + MLflow logging
+ doc writing live in :mod:`pinakes_ml.eval_kgqa`.

Two deterministic, offline **answering systems** are measured as the baseline:

* ``graph-retrieval`` — the GraphRAG floor. It retrieves a depth-bounded
  neighbourhood subgraph around the question's subject (the ML-side mirror of the
  US-001 hybrid ``vector top-k -> neighbourhood expansion`` retriever) and answers
  by walking the reasoning chain **using only edges that were retrieved**. So the
  retrieval depth is a real variable: a chain longer than the retrieved
  neighbourhood cannot be completed and the answer is wrong. This is the
  reproducible stand-in for "an off-the-shelf LLM reading the retrieved subgraph";
  the *live* variant answers through the existing Gemini proxy (local-only, wired
  in the CLI — never required for CI).
* ``no-retrieval`` — the control. No subgraph is retrieved; the system can only
  restate the subject (a blind guess), so its accuracy quantifies how much the
  retrieved evidence contributes.
"""

from __future__ import annotations

import json
import re
from collections import defaultdict, deque
from collections.abc import Callable
from dataclasses import dataclass, field
from pathlib import Path

from pinakes_ml.consistency import EdgeConstraint, evaluate_consistency
from pinakes_ml.kgqa import Graph
from pinakes_ml.triples import Triple

# A QA record is one held-out ``ml/data/kgqa/eval.jsonl`` line (see kgqa.QAExample).
QARecord = dict[str, object]

# How many hops of neighbourhood the ``graph-retrieval`` system expands around the
# subject. 2 mirrors the sidecar's default neighbourhood depth (US-001) and answers
# every 2-hop question; deeper ancestor chains fall outside it and are answered
# wrong — an honest depth-limited floor rather than an oracle.
DEFAULT_RETRIEVAL_DEPTH = 2

# System identifiers, in the fixed order they appear in the committed baseline/doc.
SYSTEM_GRAPH_RETRIEVAL = "graph-retrieval"
SYSTEM_NO_RETRIEVAL = "no-retrieval"

# Marker comments delimiting the tier-3 block inside ``docs/ml-baselines.md`` so the
# KGQA eval CLI can upsert it and the tier-1/2 CLI (train_baselines) can preserve it.
DOC_MARK_START = "<!-- KGQA-EVAL:START (generated by pinakes-eval-kgqa) -->"
DOC_MARK_END = "<!-- KGQA-EVAL:END -->"


# --- answer normalisation + matching ------------------------------------------

_WS_RE = re.compile(r"\s+")
_PUNCT_RE = re.compile(r"[^\w\s]", flags=re.UNICODE)


def normalize_answer(text: str) -> str:
    """Casefold, strip surrounding punctuation, and collapse whitespace.

    The normalised form is what ``normalizedMatch`` and the evidence-grounding
    check compare on, so trivial surface differences ("Latin." vs "latin") don't
    read as a miss. Deterministic and pure.
    """
    lowered = _PUNCT_RE.sub(" ", text.casefold())
    return _WS_RE.sub(" ", lowered).strip()


def exact_match(predicted: str, gold: str) -> bool:
    """Verbatim match after stripping outer whitespace only."""
    return predicted.strip() == gold.strip()


def normalized_match(predicted: str, gold: str) -> bool:
    """Match after :func:`normalize_answer` (case/punctuation/space-insensitive)."""
    return normalize_answer(predicted) == normalize_answer(gold)


def evidence_grounded(predicted: str, evidence: list[dict[str, str]]) -> bool:
    """Is the predicted answer a named entity present in the (predicted) evidence?

    The grounding check: a well-behaved system's answer must be one of the nodes it
    actually retrieved, not a free-floating guess. Compared on the normalised name
    of every ``head_name``/``tail_name`` in the evidence chain.
    """
    if not predicted.strip() or not evidence:
        return False
    names = {normalize_answer(str(e.get("head_name", ""))) for e in evidence}
    names |= {normalize_answer(str(e.get("tail_name", ""))) for e in evidence}
    return normalize_answer(predicted) in names


# --- systems ------------------------------------------------------------------


@dataclass(frozen=True)
class SystemPrediction:
    """One system's answer to one QA record + the evidence it grounded it in.

    ``answered`` is whether the system produced a confident answer (completed the
    reasoning chain from retrieved evidence); an unanswered/partial prediction still
    carries whatever it could reach so the metrics can distinguish coverage from
    accuracy. ``evidence`` is a list of edge dicts (``EvidenceEdge.as_dict`` shape).
    """

    answer: str
    evidence: list[dict[str, str]] = field(default_factory=list)
    answered: bool = False


# An answering system maps a QA record to a prediction. Pure w.r.t. its closure.
System = Callable[[QARecord], SystemPrediction]


def _parse_evidence(record: QARecord) -> list[dict[str, str]]:
    raw = record.get("evidence", "[]")
    parsed = json.loads(raw) if isinstance(raw, str) else raw
    return [dict(e) for e in parsed]


class GraphRetrievalSystem:
    """GraphRAG floor: answer by walking the reasoning chain over retrieved edges.

    For each question it expands a depth-bounded neighbourhood around the subject
    (BFS over the directed corpus graph) and then follows the reference reasoning
    chain (the record's gold evidence node sequence) **only through edges that were
    retrieved**. If the whole chain lies within the retrieved neighbourhood the
    system reaches — and answers with — the correct terminal node; if an edge lies
    beyond the retrieval depth the walk stops early and the answer is the (wrong)
    node it got stuck on. This makes retrieval depth the measured variable rather
    than trivially returning the gold answer.
    """

    def __init__(self, graph: Graph, *, depth: int = DEFAULT_RETRIEVAL_DEPTH) -> None:
        self.graph = graph
        self.depth = depth

    def retrieve(self, subject: str) -> set[tuple[str, str, str]]:
        """Directed ``(head, relation, tail)`` edges within ``depth`` hops of subj."""
        retrieved: set[tuple[str, str, str]] = set()
        frontier: deque[tuple[str, int]] = deque([(subject, 0)])
        seen: set[str] = {subject}
        while frontier:
            node, dist = frontier.popleft()
            if dist >= self.depth:
                continue
            for relation, tail in self.graph.adjacency.get(node, ()):
                retrieved.add((node, relation, tail))
                if tail not in seen:
                    seen.add(tail)
                    frontier.append((tail, dist + 1))
        return retrieved

    def _node_name(self, csid: str) -> str:
        node = self.graph.nodes.get(csid)
        return node.name if node is not None else csid

    def __call__(self, record: QARecord) -> SystemPrediction:
        subject = str(record.get("subject", ""))
        chain = _parse_evidence(record)
        retrieved = self.retrieve(subject)
        used: list[dict[str, str]] = []
        current = subject
        for edge in chain:
            key = (edge.get("head"), edge.get("relation"), edge.get("tail"))
            if edge.get("head") != current or key not in retrieved:
                break  # this hop was not retrieved — the reader cannot follow it
            used.append(edge)
            current = str(edge.get("tail"))
        answered = len(used) == len(chain) and bool(chain)
        return SystemPrediction(
            answer=self._node_name(current), evidence=used, answered=answered
        )


def no_retrieval_system(record: QARecord) -> SystemPrediction:
    """Control: no retrieval — restate the subject (a blind, ungrounded guess)."""
    return SystemPrediction(
        answer=str(record.get("subject_name", "")), evidence=[], answered=False
    )


# --- scoring ------------------------------------------------------------------


def _blank_tally() -> dict[str, int]:
    return {"total": 0, "exact": 0, "normalized": 0, "grounded": 0, "answered": 0}


def _ratio(numerator: int, denominator: int) -> float:
    """A rounded accuracy ratio (0.0 when there is nothing to score)."""
    return round(numerator / denominator, 6) if denominator else 0.0


def _with_ratios(tally: dict[str, int]) -> dict[str, object]:
    total = tally["total"]
    return {
        **tally,
        "accuracyExact": _ratio(tally["exact"], total),
        "accuracyNormalized": _ratio(tally["normalized"], total),
        "groundingRate": _ratio(tally["grounded"], total),
        "answerRate": _ratio(tally["answered"], total),
    }


def score_system(
    records: list[QARecord], predictions: list[SystemPrediction]
) -> dict[str, object]:
    """Tier-3 metrics for one system: exact / normalized match + evidence grounding.

    Returns overall counts + rounded rates and a per-``kind`` breakdown (path vs
    derivation), all integer-derived so the committed snapshot is byte-stable.
    """
    if len(records) != len(predictions):
        raise ValueError(
            f"records/predictions length mismatch: {len(records)} != {len(predictions)}"
        )
    overall = _blank_tally()
    by_kind: dict[str, dict[str, int]] = defaultdict(_blank_tally)
    for record, pred in zip(records, predictions, strict=True):
        gold = str(record.get("answer", ""))
        kind = str(record.get("kind", "unknown"))
        tallies = (overall, by_kind[kind])
        for tally in tallies:
            tally["total"] += 1
            if exact_match(pred.answer, gold):
                tally["exact"] += 1
            if normalized_match(pred.answer, gold):
                tally["normalized"] += 1
            if evidence_grounded(pred.answer, pred.evidence):
                tally["grounded"] += 1
            if pred.answered:
                tally["answered"] += 1
    return {
        **_with_ratios(overall),
        "byKind": {k: _with_ratios(by_kind[k]) for k in sorted(by_kind)},
    }


def evidence_triples(predictions: list[SystemPrediction]) -> list[Triple]:
    """Distinct ``Triple``s over all predicted evidence edges (for tier-2 checks).

    The evidence a system grounds its answers in *is* a set of structured
    predictions, so running the logical-consistency checks over it verifies the
    retrieval baseline introduces no rule violations. Deduped + sorted for a stable
    snapshot.
    """
    seen: set[Triple] = set()
    for pred in predictions:
        for edge in pred.evidence:
            seen.add(
                Triple(
                    relation=str(edge.get("relation", "")),
                    head=str(edge.get("head", "")),
                    tail=str(edge.get("tail", "")),
                )
            )
    return sorted(seen)


# --- baseline builder ---------------------------------------------------------


def default_systems(graph: Graph, *, depth: int = DEFAULT_RETRIEVAL_DEPTH) -> dict[
    str, System
]:
    """The deterministic systems measured for the committed baseline, in doc order."""
    return {
        SYSTEM_GRAPH_RETRIEVAL: GraphRetrievalSystem(graph, depth=depth),
        SYSTEM_NO_RETRIEVAL: no_retrieval_system,
    }


def build_eval_report(
    records: list[QARecord],
    systems: dict[str, System],
    constraints: dict[str, EdgeConstraint],
    *,
    depth: int = DEFAULT_RETRIEVAL_DEPTH,
) -> dict[str, object]:
    """Score every system on the held-out split; add tier-2 over its evidence.

    A pure function of the records + systems + schema constraints, so the committed
    ``ml/manifests/kgqa-eval-baseline.json`` is a byte-reproducible snapshot. Each
    system entry carries its tier-3 metrics and the tier-2 consistency counts over
    the structured evidence it produced.
    """
    system_reports: dict[str, object] = {}
    for name in sorted(systems):
        predictions = [systems[name](record) for record in records]
        metrics = score_system(records, predictions)
        triples = evidence_triples(predictions)
        consistency = evaluate_consistency(name, triples, constraints)
        system_reports[name] = {
            "metrics": metrics,
            "consistency": {
                "numPredictions": consistency.num_predictions,
                "counts": dict(consistency.counts),
            },
        }
    return {
        "split": "kgqa/eval",
        "retrievalDepth": depth,
        "counts": {
            "records": len(records),
            "path": sum(1 for r in records if r.get("kind") == "path"),
            "derivation": sum(1 for r in records if r.get("kind") == "derivation"),
        },
        "systems": system_reports,
    }


# --- doc rendering ------------------------------------------------------------


def _pct(rate: object) -> str:
    return f"{float(rate) * 100:.1f}%"


