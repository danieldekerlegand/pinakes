def extract_marked_section(doc_text: str) -> str | None:
    """The tier-3 block (incl. markers) currently in the doc, or ``None`` if absent.

    Lets the tier-1/2 CLI preserve a KGQA block when it rewrites the doc from
    scratch, so the two cooperating CLIs don't clobber each other's section.
    """
    start = doc_text.find(DOC_MARK_START)
    end = doc_text.find(DOC_MARK_END)
    if start == -1 or end == -1 or end < start:
        return None
    return doc_text[start : end + len(DOC_MARK_END)]


def upsert_marked_section(doc_text: str, section: str) -> str:
    """Insert or replace the marked tier-3 block. Idempotent; appends if absent.

    ``section`` is the full :func:`render_kgqa_section` output (already
    marker-wrapped + trailing newline). Replacing an existing block keeps the doc
    byte-stable across reruns.
    """
    existing = extract_marked_section(doc_text)
    body = section if section.endswith("\n") else section + "\n"
    if existing is not None:
        replaced = doc_text.replace(existing, body.rstrip("\n"), 1)
        return replaced if replaced.endswith("\n") else replaced + "\n"
    prefix = doc_text if doc_text.endswith("\n") else doc_text + "\n"
    return f"{prefix}\n{body}"


def load_records(path: Path | str) -> list[QARecord]:
    """Load a KGQA JSONL split into records (thin wrapper over the file reader)."""
    text = Path(path).read_text(encoding="utf-8")
    return [json.loads(line) for line in text.splitlines() if line]
