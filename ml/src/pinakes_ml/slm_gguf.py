def merge_adapter(
    plan: ConversionPlan,
) -> Path:  # pragma: no cover - needs the model + peft, local-only
    """Fold the LoRA adapter into the base weights and save fp16 HF weights.

    ``convert_hf_to_gguf.py`` reads a plain HF checkpoint, not an adapter, so the
    merge is a required step rather than an optimization. fp16 because it is the
    converter's lossless input type — the quantization happens once, downstream,
    where it can be measured.
    """
    import torch
    from peft import PeftModel
    from transformers import AutoModelForCausalLM, AutoTokenizer

    from pinakes_ml.slm_finetune import free_device_memory

    model = AutoModelForCausalLM.from_pretrained(
        plan.base_model, torch_dtype=torch.float16
    )
    merged = PeftModel.from_pretrained(model, str(plan.adapter_dir)).merge_and_unload()
    plan.merged_dir.mkdir(parents=True, exist_ok=True)
    merged.save_pretrained(str(plan.merged_dir), safe_serialization=True)
    # The trainer saved the tokenizer next to the adapter; prefer it, so the GGUF
    # carries the exact vocabulary the run was scored with.
    tokenizer_src = (
        plan.adapter_dir
        if (plan.adapter_dir / "tokenizer_config.json").exists()
        else plan.base_model
    )
    AutoTokenizer.from_pretrained(str(tokenizer_src)).save_pretrained(
        str(plan.merged_dir)
    )
    del merged, model
    free_device_memory()
    return plan.merged_dir


class LlamaCppRuleModel:  # pragma: no cover - needs a GGUF + native runtime
    """A GGUF under llama.cpp behind the :class:`RuleModel` seam.

    Deliberately the *same* seam the HF model is scored through, fed the *same*
    :func:`~pinakes_ml.slm_finetune.format_inference_prompt` string, decoded
    greedily — so the parity delta is the runtime and the quantization, not the
    harness. ``logits_all`` is on because :meth:`eval_loss` needs per-position
    logits; it costs memory but keeps the frozen metric list complete.
    """

    def __init__(
        self,
        gguf_path: Path | str,
        *,
        n_ctx: int = 4096,
        max_new_tokens: int = GENERATION_CONTRACT["maxNewTokens"],
        seed: int = 0,
        n_gpu_layers: int = -1,
        verbose: bool = False,
    ) -> None:
        require_llama_cpp_python()
        from llama_cpp import Llama

        self.gguf_path = str(gguf_path)
        self.max_new_tokens = max_new_tokens
        self.n_ctx = n_ctx
        # Not the tokenizer's chat template: this model is prompted with the pure
        # renderer, which IS the contract. Recorded as unverifiable here rather
        # than claimed — the HF run already asserted the template equality.
        self.chat_template_verified: bool | None = None
        self.llm = Llama(
            model_path=self.gguf_path,
            n_ctx=n_ctx,
            n_gpu_layers=n_gpu_layers,
            logits_all=True,
            seed=seed,
            verbose=verbose,
        )

    def generate(self, prompt: str) -> str:
        out = self.llm.create_completion(
            format_inference_prompt(prompt),
            max_tokens=self.max_new_tokens,
            temperature=float(GENERATION_CONTRACT["temperature"]),
            top_k=int(GENERATION_CONTRACT["topK"]),
            top_p=float(GENERATION_CONTRACT["topP"]),
            stop=list(GENERATION_CONTRACT["stop"]),
        )
        return str(out["choices"][0]["text"])

    def eval_loss(self, pairs: Sequence[tuple[str, str]]) -> float | None:
        """Teacher-forced mean loss on the reference completions.

        The llama.cpp mirror of :meth:`HFRuleModel.eval_loss`: score the full
        training text, then average cross-entropy over the **completion** tokens
        only (the prompt positions are skipped, which is what HF's ``-100``
        masking does). Returns ``None`` if the runtime exposes no logits — an
        absent metric, never a fabricated one.
        """
        import numpy as np

        losses: list[float] = []
        for prompt, reference in pairs:
            prompt_ids = self.llm.tokenize(
                format_inference_prompt(prompt).encode("utf-8"), special=True
            )
            full_ids = self.llm.tokenize(
                format_training_text(prompt, reference).encode("utf-8"), special=True
            )
            if len(full_ids) <= len(prompt_ids) or len(full_ids) > self.n_ctx:
                continue
            self.llm.reset()
            self.llm.eval(full_ids)
            scores = np.asarray(self.llm.scores[: len(full_ids)], dtype=np.float64)
            if scores.ndim != 2 or not scores.any():
                return None
            steps: list[float] = []
            for position in range(len(prompt_ids) - 1, len(full_ids) - 1):
                logits = scores[position]
                shifted = logits - logits.max()
                log_z = float(np.log(np.exp(shifted).sum()))
                steps.append(log_z - float(shifted[full_ids[position + 1]]))
            if steps:
                losses.append(sum(steps) / len(steps))
        return round(sum(losses) / len(losses), 6) if losses else None


def llama_cpp_runtime_info(
    root: Path | str,
) -> dict[str, Any]:  # pragma: no cover - filesystem/VCS dependent
    """What the parity column was scored *in* — recorded, not assumed."""
    import subprocess

    info: dict[str, Any] = {"llamaCppDir": str(root)}
    try:
        info["llamaCppCommit"] = subprocess.run(
            ["git", "-C", str(root), "rev-parse", "--short", "HEAD"],
            capture_output=True, text=True, check=True, timeout=15,
        ).stdout.strip()
    except Exception:  # noqa: BLE001 - provenance is best-effort
        info["llamaCppCommit"] = ""
    try:
        import llama_cpp

        info["llamaCppPython"] = getattr(llama_cpp, "__version__", "")
    except ImportError:
        info["llamaCppPython"] = ""
    return info


