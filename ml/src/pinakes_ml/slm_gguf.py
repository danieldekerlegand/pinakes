"""GGUF conversion + llama.cpp parity check (slm-pilot US-004).

The pilot's **deployment leg**: take the US-003 fine-tuned adapter, merge it into
the base weights, convert to GGUF, quantize to the exact quant Insimul already
deploys (``Q4_K_M`` via node-llama-cpp), and then answer the only question that
matters about that pipeline — *does the model still behave the same?*

The parity check is deliberately narrow. The GGUF is scored by the **same tier-4
adherence harness** on the **same frozen eval set**, through the **same
:class:`~pinakes_ml.slm_finetune.RuleModel` seam** and the **same ChatML prompt
string** as the HF-stack run, so the only variable between the two columns is the
runtime + quantization. Anything else and a difference could be the harness.

The acceptability judgment is **not made here**: ``docs/slm-pilot-protocol.md`` §5
froze it before any training run — *"Q4_K_M under llama.cpp degrades ``fullyValid``
by ≤ 2pp vs the HF stack on the same eval set"* (:data:`QUANT_BUDGET_PP`). This
module computes the observed degradation and compares it to that frozen number;
US-004 could not pick a threshold after seeing the drop, which was the point.

The third deliverable lives here too and is the one Insimul actually consumes:
:func:`build_prompt_contract` — the **exact strings** ``LocalAIService`` must send.
It is a pure function of the pipeline's own prompt renderers (no fixtures, no
corpus), so the committed ``ml/manifests/slm-prompt-contract.json`` is snapshot-
gated in CI and cannot drift from what the model was trained on. Prose half:
``docs/slm-prompt-contract.md``.

Shape, per ``ml/CLAUDE.md``: pure core (path plans, argv builders, the parity
arithmetic, the contract, the doc block) with **no heavy imports at module load**,
plus lazily-imported conversion/inference that never runs in CI. ``llama-cpp-python``
and the llama.cpp checkout are undeclared, local-only dependencies — same stance as
``trl``/``peft`` (see ``pyproject.toml``).

CLI: :mod:`pinakes_ml.export_gguf`. Runbook: ``docs/slm-pilot-runbook.md`` §US-004.
"""

