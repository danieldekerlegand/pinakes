"""Rule-adherence eval tier — the VESPACE port (insimul-bridge US-004).

The **fourth** eval tier, alongside link-prediction metrics (tier 1), logical
consistency (tier 2) and KGQA accuracy (tier 3): *can a generated Prolog rule
ever fire in the world it was authored for?*

Given a set of candidate rules (LLM output, or a world's own rule set) plus a
**world context** distilled from a ``CanonicalWorldExport`` (US-003's bridge-2
artifact), it reports five families of numbers:

``parseRate``
    Fraction of candidate rules whose Prolog text parses into clauses.
``structuralValidity``
    Fraction free of the mechanical authoring failures the Insimul rule
    validator catches (sentence atoms, literal actor atoms, family-prefix
    predicates, opaque effect payloads, a body that never touches a head var).
``schemaValidity``
    Fraction whose every body goal names a predicate the world's vocabulary
    actually declares — the *predicate-invention* rate, inverted.
``referentialIntegrity``
    Fraction whose entity-position atoms all resolve to entities in the world.
``reachabilityCharitable`` / ``reachabilityStrict`` / ``fireabilityIndex``
    The VESPACE reachability model: are a rule's conditions producible at all,
    given the character-creation layer and the action set?

Self-contained + PURE (stdlib only), like ``consistency.py``: it does **not**
import Insimul code. The metric definitions are reimplemented from Insimul's
``reachability-analyzer.ts`` / ``insimul-reachability-analyzer.ts`` and its
validator stack; every formula and constant is cited in
:doc:`../../../docs/rule-adherence-tier.md`. Everything is a pure function of
(rules, world context), sorted and wall-clock-free, so :func:`build_report` is
byte-reproducible — the same inputs yield the same committed baseline (a git
no-op), the same ratchet shape as the other eval tiers.
"""

