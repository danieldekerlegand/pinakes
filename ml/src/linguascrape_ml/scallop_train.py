"""Rule-guided link prediction — the neurosymbolic pilot's core (Phase 5, US-003).

A **differentiable rule-guided link predictor**: a neural edge scorer (over the
committed PyKEEN entity embeddings) provides soft edge probabilities, and the
corpus's Horn rules propagate that evidence through the graph before the loss is
taken. The pilot's target is ``DESCENDS_FROM`` (with the recursive *ancestor*
transitive-closure rule — the "ancestor chains" of the acceptance criterion) plus
``BORROWED_FROM`` (no sound transitive rule — scored by the neural predicate alone,
documented honestly).

**The model.** For a candidate edge ``(h, r, t)``:

* the neural predicate scores the direct edge, ``p_direct = σ(MLP_r([h; t; h⊙t;
  |h−t|]))`` over the frozen embeddings — the *soft edge probability* the pilot needs;
* the symbolic layer takes the ``train`` base facts of ``r``, each weighted by the
  **same** neural predicate, and propagates them through the ancestor rule under
  Scallop's **min-max-prob** provenance: ``Pr[ancestor(h, t)] = max over paths of
  (min edge probability along the path)`` — the exact bottleneck-/widest-path
  semantics, computed here by :func:`minmax_widths` (a bounded-hop, fully
  differentiable relaxation);
* the rule-guided score is their disjunction, ``score = max(p_direct,
  Pr[ancestor(h, t)])`` — under min-max-prob a rule with two bodies (direct + the
  recursive one) *is* the max of the two.

So the neural scorer learns edge probabilities that are useful **both** directly and
after the rule propagates them across multi-hop descent chains; a held-out edge that
no direct signal reaches can still be scored through a chain of soft train edges.

**Why this is the faithful Scallop program.** The very same rule
(``ancestor(x, y) = descends_from(x, y); descends_from(x, z) and ancestor(z, y)``)
under scallopy's ``minmaxprob`` provenance computes exactly :func:`minmax_widths`, so
the engine-free reference here and the scallopy backend
(:func:`build_scl_program` / the local-only run in
:mod:`linguascrape_ml.train_scallop`) agree by construction — the same discipline
US-001 used to validate the boolean smoke against
:func:`linguascrape_ml.scallop.transitive_closure` when scallopy could not run on
this Linux/py3.11 host. With every edge probability set to ``1.0`` the min-max
reachable set collapses to that boolean transitive closure, which is the tie-in the
tests assert.

Everything here keeps ``torch`` imports **lazy** (module top stays light, so
``import linguascrape_ml`` never pulls the heavy stack — the workspace rule the
baselines/finetune modules follow). The pure pieces — the min-max semantics, the
ranking metrics, the helped/hurt/neutral verdict, the ``.scl`` emission, and the
doc-section renderer — are unit-tested on tiny fixtures in CI; the actual training
run (torch, local) lives in the thin CLI :mod:`linguascrape_ml.train_scallop`.
"""

